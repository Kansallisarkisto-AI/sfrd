"""
The heuristic solver in this file is almost entirely generated by Claude,
based on the CP-SAT solver in boxfit.py which has had much more love and care
put into it. Unfortunately the exact solver is way too slow.

The two strategies seem alright for tabular content but no guarantees for others.

Claude output starts:

Pairwise/star coordinate descent alternative to the CP-SAT box-fitting solver.

Every constraint in this problem is naturally a coupled pair of edges that
must stay `gap` apart:
  * a cell's own (x0, x1) and (y0, y1) -- must stay >= min_size apart
  * two touching cells' facing edges -- must stay >= gap apart (whichever of
    the 4 possible facings currently applies)

The base move optimizes one such pair at a time: given two coupled edges, do
an exact small 2-D search over both simultaneously, holding everything else
fixed, and take whichever combination is cheapest.

That's not enough when an edge is shared by *more than one* constraint on the
same side -- e.g. one wide cell sitting below two narrower cells side by side.
The wide cell's top edge (y0) is coupled separately to each of the two cells'
bottom edges (y1) above it, via two different constraints. Solving those two
pairs one at a time only ever asks "what's best for this edge and *one*
neighbor", so it can get stuck: moving the shared edge further would let
*both* neighbors settle into cheaper positions, but neither pairwise solve on
its own sees that combined benefit, and the sweep just ping-pongs between two
locally-cheap-but-jointly-bad states.

To fix that we add a second kind of move, `solve_star`: whenever an edge is
tied via multiple *currently binding* constraints to distinct partner edges
that are all on the same side of the gap (all of them need `partner >= v +
gap`, or all need `partner <= v - gap`), we jointly search over the shared
edge together with every one of its partners at once. For a fixed candidate
value of the shared edge, each partner's optimal value/cost is independent of
the others (only the feasible range depends on the shared edge), so this is
solved exactly and efficiently with a prefix/suffix-min sweep per partner,
not a combinatorial search. We alternate star sweeps with the plain pairwise
sweeps until a full round of both changes nothing.
"""
